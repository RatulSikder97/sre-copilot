"""Render an ``IncidentReport`` as Markdown."""

from __future__ import annotations

from sre_copilot.models import HypothesisStatus, IncidentReport


def _cite(ids: list[str]) -> str:
    return f" [{', '.join(ids)}]" if ids else ""


def render_markdown(report: IncidentReport) -> str:
    out: list[str] = []
    d = report.draft
    title = d.title if d else f"Investigation {report.investigation_id}"
    out.append(f"# {title}")
    out.append("")
    tools = (
        "tool outputs are real, recorded from the kind demo cluster"
        if report.tools_mode == "fixtures"
        else "tool outputs are live"
    )
    banner = (
        f"> **REPLAY MODE** - scripted model turns (no LLM call); {tools}."
        if report.mode == "replay"
        else f"> Generated by `{report.model}`; {tools}."
    )
    out.append(banner)
    u = report.usage
    out.append(
        f"> `{report.investigation_id}` | status **{report.status.value}** "
        f"| model `{report.model}` "
        f"| {u.steps} steps, {u.tool_calls} tool calls, ~{u.total_tokens} tokens, "
        f"{u.elapsed_seconds:.1f}s"
    )
    out.append("")
    if report.error:
        out.append(f"**Error:** {report.error}")
        out.append("")

    if d:
        out += [f"**Severity:** {d.severity}", "", "## Summary", d.summary, ""]
        out += ["## Impact", d.impact, ""]
        out.append("## Timeline")
        out += [f"- `{t.time}` {t.event}{_cite(t.evidence_ids)}" for t in d.timeline]
        out.append("")
        rc = d.root_cause
        out += [
            "## Root cause hypothesis",
            f"**{rc.hypothesis}** (confidence {rc.confidence:.0%}){_cite(rc.evidence_ids)}",
            "",
            rc.reasoning,
            "",
        ]

    if report.hypotheses:
        out.append("## Hypotheses considered")
        for h in report.hypotheses:
            mark = {
                HypothesisStatus.SUPPORTED: "supported",
                HypothesisStatus.RULED_OUT: "ruled out",
                HypothesisStatus.OPEN: "open",
            }[h.status]
            out.append(
                f"- **{h.id}** ({mark}, {h.confidence:.0%}) {h.statement}{_cite(h.evidence_ids)}"
            )
            if h.notes:
                out.append(f"  - {h.notes}")
        out.append("")

    if d:
        out.append("## Proposed remediation")
        for i, step in enumerate(d.remediation, 1):
            ref = f" -> proposal `{step.proposal_id}`" if step.proposal_id else ""
            out.append(f"{i}. {step.step} _(risk: {step.risk})_{ref}")
        out.append("")

    if report.proposals:
        out.append("## Approval queue")
        out.append("| proposal | action | status | dry run | expires |")
        out.append("|---|---|---|---|---|")
        for p in report.proposals:
            out.append(
                f"| `{p.id}` | {p.action.describe()} | {p.status.value} | "
                f"{p.dry_run.summary} | {p.expires_at:%Y-%m-%d %H:%M:%SZ} |"
            )
        for p in report.proposals:
            if p.dry_run.diff:
                out.append("")
                out.append(f"Dry-run diff for `{p.id}`:")
                out.append("```diff")
                out += [f"~ {line}" for line in p.dry_run.diff]
                out.append("```")
        out.append("")
        out.append(
            "Approve with `sre-copilot approve <proposal>`; unapproved proposals expire "
            "(default deny)."
        )
        out.append("")

    if report.evidence:
        out.append("## Evidence")
        for e in report.evidence:
            link = f" ([link]({e.link}))" if e.link else ""
            err = " **(error)**" if e.is_error else ""
            out.append(f"- **{e.id}** `{e.tool}`{err}: {e.summary}{link}")
        out.append("")

    cited = list(d.runbook_refs) if d else []
    consulted = [r for r in report.runbooks if r not in cited]
    if cited or consulted:
        out.append("## Runbooks")
        out += [f"- `{r}` (cited)" for r in cited]
        out += [f"- `{r}` (retrieved)" for r in consulted]
        out.append("")

    if d and d.follow_ups:
        out.append("## Follow-ups")
        out += [f"- {f}" for f in d.follow_ups]
        out.append("")
    return "\n".join(out).rstrip() + "\n"
